// Shuffle questions & choices helper
export function getQuestionsForLevel(category, level, usedIndices = []) {
  const pool = QUESTIONS[category];
  if (!pool) return [];

  const available = pool
    .map((q, i) => ({ ...q, originalIndex: i }))
    .filter(q => !usedIndices.includes(q.originalIndex));

  // Shuffling
  const shuffled = [...available].sort(() => Math.random() - 0.5);
  const count = 4;
  const selected = shuffled.slice(0, count);

  return selected.map(q => {
    const answers = [...q.a];
    const correctAnswer = answers[q.correct];
    // Shuffle answers
    for (let i = answers.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [answers[i], answers[j]] = [answers[j], answers[i]];
    }
    return {
      question:     q.q,
      answers,
      correctIndex: answers.indexOf(correctAnswer),
      originalIndex: q.originalIndex,
    };
  });
}
